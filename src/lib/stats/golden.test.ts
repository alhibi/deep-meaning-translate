/**
 * Golden fixture for the whole statistics derivation (task 5.3).
 *
 * Every number the statistics screen shows is derived from one local archive. The
 * derivation is memoised per archive array (identity) for cost, so this test pins the
 * complete output of the pipeline on a fixed archive: a change in any derived number —
 * from a refactor of the single-pass loops, a memo key that conflates two time zones, or
 * a changed classification rule — fails here instead of only in a screenshot.
 *
 * The archive covers both directions, a user correction, a model tag, a legacy row
 * without a version, a duplicate id, local estimates and a row near a time-zone boundary.
 */

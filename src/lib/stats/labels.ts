export const STATS_DICT: Record<Locale, Dict> = { en, ar, de };
export const CATEGORY_DICT = CAT;
export type StatsKey = keyof Dict;

export function statsT(locale: Locale) {
  const d = STATS_DICT[locale] ?? en;
  return (key: StatsKey, vars?: Record<string, string | number>) => {
    let s: string = d[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function categoryLabel(
  locale: Locale,
  dim: "kind" | "domain" | "intent" | "register",
  id: string,
): string {
  const table = CAT[locale]?.[dim] as Record<string, string> | undefined;
  return table?.[id] ?? (CAT.en[dim] as Record<string, string>)[id] ?? id;
}

/** Latin digits everywhere so numbers align in charts across all three interface languages. */
export function numberFormat(locale: Locale, opts?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(`${locale}-u-nu-latn`, opts);
}
